class Npx1_Channel_Selector:
    """
    Channel selector for Neuropixels 1.0 (single shank) via the Open Ephys GUI.

    Capabilities
    ------------
    - oe_connect(): connect to OE GUI, find Neuropix-PXI, cache bs/port/dock
    - select_bank(bank): select bank 'A'/'B'/'C'
    - select_electrodes(eids_1based): select explicit 1-based electrode indices (1..960)
    - sweep_all_banks(record_s=60, order=('A','B','C')): record each bank sequentially

    Notes
    -----
    - NP1.0 has 960 selectable sites; 384 can be active at once.
    - Bank A: 0..383; Bank B: 384..767; Bank C: 768..959 plus backfill 576..767 (to reach 384).
      (We keep 0-based internally and convert to 1-based only when sending to OE.)
    - For NP1.0, dock is always 1 in the NP SELECT command.
    """

    def __init__(self):
        # Probe constants
        self.n_shanks = 1
        self.n_elec_total = 960
        self.n_elec_per_bank = 384

        # Cosmetic layout (optional; in case you later plot selections)
        self.dx = 16   # μm
        self.dy = 20   # μm
        self.n_cols = 4
        self.electrode_xy = np.zeros((self.n_elec_total, 2), dtype=float)
        for i in range(self.n_elec_total):
            col = i % self.n_cols
            row = i // self.n_cols
            self.electrode_xy[i] = [col * self.dx, row * self.dy]

        # OE handles
        self.gui = None
        self.npx_pxi_processor_id = None
        self.oe_info = None  # dict with processor_id, basestation, port, dock

        # Cache of current selection (0-based)
        self.current_eids0 = np.array([], dtype=int)

    # ---------- Open Ephys interaction ----------
    @staticmethod
    def query_oe_processors(port="37497"):
        r = requests.get(f"http://localhost:{port}/api/processors")
        r.raise_for_status()
        return r.json()

    def _query_np_info(self):
        info_str = self.gui.config(self.npx_pxi_processor_id, "NP INFO")["info"]
        info_str = info_str.replace("false", "False").replace("true", "True")
        return eval(info_str)

    def oe_connect(self):
        """Connect to OE, locate Neuropix-PXI, and cache basestation/port/dock for the first probe."""
        try:
            procs = self.query_oe_processors()["processors"]
        except requests.exceptions.RequestException as e:
            raise ConnectionError("Could not connect to Open Ephys GUI at localhost:37497.") from e

        for p in procs:
            if p["name"] == "Neuropix-PXI":
                self.npx_pxi_processor_id = p["id"]
                break
        if self.npx_pxi_processor_id is None:
            raise RuntimeError("Neuropix-PXI processor not found in OE GUI.")

        # Initialize OE HTTP client and probe info
        self.gui = OpenEphysHTTPServer()

        npx_info = self._query_np_info()
        probe0 = npx_info["probes"][0]  # use first detected probe by default
        # NP1.0 always uses dock=1 in NP SELECT
        self.oe_info = dict(
            processor_id=self.npx_pxi_processor_id,
            basestation=probe0["slot"],   # bs
            port=probe0["port"],          # port
            dock=1,                       # NP1.0
        )

        # Sanity ping + short acquire
        self.gui.config(self.npx_pxi_processor_id, "NP INFO")
        self.gui.acquire(1)

    # ---------- Bank definitions (0-based internally) ----------
    @property
    def bank_A_eids0(self):
        return np.arange(0, 384, dtype=int)

    @property
    def bank_B_eids0(self):
        return np.arange(384, 768, dtype=int)

    @property
    def bank_C_eids0(self):
        head = np.arange(768, 960, dtype=int)   # 192
        tail = np.arange(576, 768, dtype=int)   # +192 = 384
        return np.concatenate([head, tail])

    def get_bank(self, bank: str):
        bank = bank.upper()
        if bank == "A":
            return self.bank_A_eids0
        if bank == "B":
            return self.bank_B_eids0
        if bank == "C":
            return self.bank_C_eids0
        raise ValueError("bank must be 'A', 'B', or 'C'")

    # ---------- Selection helpers ----------
    def _send_np_select(self, eids0, debug=False):
        if self.gui is None or self.oe_info is None:
            raise RuntimeError("Not connected to OE. Call oe_connect() first.")
        eids1 = (np.asarray(eids0, dtype=int) + 1).astype(str)  # 1-based for OE
        eid_str = " ".join(eids1.tolist())
        d = self.oe_info
        cmd = f'NP SELECT {d["basestation"]} {d["port"]} {d["dock"]} {eid_str}'
        if debug:
            print(cmd)
        self.gui.config(d["processor_id"], cmd)
        self.current_eids0 = np.asarray(eids0, dtype=int)

    def select_bank(self, bank: str, debug=False):
        """Select a single bank ('A','B','C')."""
        self._send_np_select(self.get_bank(bank), debug=debug)

    def select_electrodes(self, eids_1based, debug=False):
        """Select explicit 1-based electrodes (1..960)."""
        e0 = np.asarray(eids_1based, dtype=int) - 1
        if np.any(e0 < 0) or np.any(e0 >= self.n_elec_total):
            raise ValueError("Electrode indices out of range for NP1.0 (1..960).")
        self._send_np_select(e0, debug=debug)

    def sweep_all_banks(self, record_s=60, order=("A", "B", "C"), debug=False):
        """Record each bank for record_s seconds (requires OE signal chain ready to record)."""
        if self.gui is None:
            raise RuntimeError("Call oe_connect() first.")
        for b in order:
            self.select_bank(b, debug=debug)
            self.gui.record(record_s)

    # ---------- Optional conveniences ----------
    def get_current_electrodes_1based(self):
        return (self.current_eids0 + 1).tolist()

    def get_current_xy(self):
        if self.current_eids0.size == 0:
            return np.empty((0, 2))
        return self.electrode_xy[self.current_eids0]


def make_npx_selector_from_gui(prefer='auto'):
    """
    Utility: connect to OE and return the appropriate selector instance.

    prefer:
        'auto'  -> inspect NP INFO (# of shanks) to decide NP1 vs NP2
        'np1'   -> force Npx1_Channel_Selector
        'np2'   -> force Npx2_Channel_Selector
    """
    if prefer == 'np1':
        sel = Npx1_Channel_Selector()
        sel.oe_connect()
        return sel
    if prefer == 'np2':
        sel = Npx2_Channel_Selector()
        sel.oe_connect()
        return sel

    # auto-detect
    # We reuse NP2's HTTP code path because it already exists in this file.
    try:
        # Instantiate a lightweight OE client to read NP INFO
        _gui = OpenEphysHTTPServer()
        # Find NP-PXI
        procs = requests.get("http://localhost:37497/api/processors").json()["processors"]
        npx_id = None
        for p in procs:
            if p["name"] == "Neuropix-PXI":
                npx_id = p["id"]
                break
        if npx_id is None:
            raise RuntimeError("Neuropix-PXI processor not found.")
        info_str = _gui.config(npx_id, "NP INFO")["info"].replace("false","False").replace("true","True")
        info = eval(info_str)
        probe0 = info["probes"][0]
        # Heuristic: NP2 has 4 shanks; NP1 has 1
        n_shanks = probe0.get("n_shanks") or probe0.get("num_shanks") or None
    except Exception:
        n_shanks = None

    if n_shanks == 1:
        sel = Npx1_Channel_Selector()
    else:
        sel = Npx2_Channel_Selector()
    sel.oe_connect()
    return sel
